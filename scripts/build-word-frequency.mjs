/**
 * Builds src/word-frequency.js: how often each English word is actually spoken
 * in this game.
 *
 * The linguist learns a tongue the way anybody does — the commonest words
 * first — so "commonest" has to mean commonest *here*, in Azhora's own talk,
 * not in some general corpus. This walks every string literal in src/ that
 * looks like prose (a space in it, long enough to be a sentence rather than an
 * id or a colour), counts the words, and writes the ranked list out as a
 * module. src/linguist.js turns the counts into running-text coverage: the
 * fraction of what you hear that a given rank accounts for.
 *
 *   node scripts/build-word-frequency.mjs
 *
 * Regenerate it whenever a lot of new dialogue lands. Nothing breaks if it is
 * stale — an unlisted word is simply one of the last you learn.
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.join(here, '..', 'src');
const out = path.join(src, 'word-frequency.js');

/** How many ranks to keep. The tail is a long list of words said once; they are the last you learn. */
const KEEP = 5000;

/** Every string literal in a source file: single, double and backtick, with escapes left alone. */
const STRINGS = /'((?:[^'\\\n]|\\.)*)'|"((?:[^"\\\n]|\\.)*)"|`((?:[^`\\]|\\.)*)`/gs;
/** A word as the renderer tokenises one: letters, with the apostrophes English keeps inside a word. */
const WORD = /[A-Za-z][A-Za-z'’]*/g;

/** Prose, not an id, a key, a colour or a css rule. */
function isProse(text) {
  if (text.length < 12 || !text.includes(' ')) return false;
  if (/[{};<>#]/.test(text)) return false;                 // css, selectors, template plumbing
  if (/\$\{/.test(text)) return false;                     // interpolation: the parts are counted separately anyway
  return /[a-z]{3}/.test(text) && text.split(' ').length >= 3;
}

const counts = new Map();
let total = 0;
const files = (await readdir(src)).filter(name => name.endsWith('.js') && name !== 'word-frequency.js').sort();
for (const name of files) {
  const source = await readFile(path.join(src, name), 'utf8');
  for (const match of source.matchAll(STRINGS)) {
    const text = match[1] ?? match[2] ?? match[3] ?? '';
    if (!isProse(text)) continue;
    for (const word of text.matchAll(WORD)) {
      const key = word[0].toLowerCase().replace(/’/g, "'");
      if (key.length > 24) continue;
      counts.set(key, (counts.get(key) ?? 0) + 1);
      total++;
    }
  }
}

const ranked = [...counts.entries()].sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1)).slice(0, KEEP);
const kept = ranked.reduce((sum, entry) => sum + entry[1], 0);
const words = ranked.map(entry => entry[0]).join(' ');
const tallies = ranked.map(entry => entry[1]);

const body = `/**
 * Generated by scripts/build-word-frequency.mjs — do not hand-edit.
 *
 * Every English word spoken in this game, commonest first: ${ranked.length.toLocaleString('en-GB')} of the
 * ${counts.size.toLocaleString('en-GB')} distinct words in ${total.toLocaleString('en-GB')} spoken words across ${files.length} modules.
 * These ${ranked.length.toLocaleString('en-GB')} account for ${(100 * kept / total).toFixed(1)}% of everything said; the rest are said once or
 * twice and are the last words a traveler picks up. src/linguist.js reads this
 * as running-text coverage, so a word's rank is how soon you learn it.
 */
export const FREQUENT_WORDS = ${JSON.stringify(words)}.split(' ');
export const WORD_TALLIES = Object.freeze([${tallies.join(',')}]);
/** Spoken words counted, including the tail this list does not name. */
export const CORPUS_WORDS = ${total};
`;
await writeFile(out, body.replace(/\n/g, '\r\n'), 'utf8');
console.log(`word-frequency.js: ${ranked.length} ranks, ${counts.size} distinct, ${total} words, ${(100 * kept / total).toFixed(1)}% coverage`);
