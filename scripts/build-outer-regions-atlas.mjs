// Read-only import. Run after refreshing both game atlas exports.
import { readFile, writeFile } from 'node:fs/promises';
import { applyGameAtlasAdjustments } from '../src/game-atlas-adjustments.js';
import { OUTER_NAMES } from '../src/outer-regions-data.js';
const source = applyGameAtlasAdjustments(JSON.parse((await readFile(new URL('../../world-builder/map/resources/examples/azhora.wwmap', import.meta.url), 'utf8')).replace(/^\uFEFF/, '')));
const names = new Set(OUTER_NAMES);
const cells = Object.values(source.hexes).filter(c => names.has(c.region)).sort((a,b) => a.r-b.r || a.q-b.q);
const keys = new Set(cells.map(c => `${c.q},${c.r}`));
const climate = Object.fromEntries(cells.map(c => [`${c.q},${c.r}`, c.climate ?? null]));
const edges = Object.entries(source.rivers).filter(([edge]) => edge.split('|').some(k => keys.has(k))).map(([edge,size]) => {
  const [a,b] = edge.split('|').map(k => k.split(',').map(Number));
  return {a,b,size};
});
await writeFile(new URL('../src/outer-regions-atlas.js', import.meta.url), `/** Generated by scripts/build-outer-regions-atlas.mjs from the read-only authored atlas. */\nexport const OUTER_CLIMATE=Object.freeze(${JSON.stringify(climate)});\nexport const OUTER_RIVER_EDGES=Object.freeze(${JSON.stringify(edges)});\n`);
console.log(`${cells.length} regional climates; ${edges.length} river edges.`);
